export function invitePage({ author, map, members, token, mine, appleReady, googleReady, devLogin }) {
  const who = members.length ? members.join(' & ') : 'someone';
  let action;
  if (!author) {
    action = `<p>Sign in to join. No join code needed.</p>${signInButtons({ appleReady, googleReady })}${devButtons(devLogin)}`;
  } else if (author.map_is_root) {
    action = '<p class="error">You’re an admin on the root map, so you can’t move to another map.</p>';
  } else if (mine && mine.members === 1 && mine.entries > 0) {
    action = `<p class="error">You already have a map with ${mine.entries} ${mine.entries === 1 ? 'entry' : 'entries'}. Joining would leave it behind, so delete those entries (or your account) first.</p>`;
  } else {
    action = `<form method="post" action="/join/${esc(token)}/accept"><button class="btn">Join this map</button></form>
      ${mine && mine.members === 1 ? '<p class="fine">Your current (empty) map will be removed.</p>' : ''}`;
  }
  const body = ticket(`
    <p class="script">You’re invited</p>
    <h1>${esc(map.title_script)} ${esc(map.title)}</h1>
    <p>${esc(who)} invited you to share their map. You’ll both be able to write entries and add photos.</p>
    ${action}`);
  return layout({ title: 'Invite', author, body, bodyClass: 'page-login', noindex: true });
}

