const fmtN = (n) => Number(n).toLocaleString('en-US');
const SEQ = ['#f1dcc4', '#e9b98f', '#df9161', '#c4532b', '#8a3119']; // paper → rust → brick

function odo(n, label, extra = '') {
  return `<div class="gauge${extra}"><div class="odometer">${[...String(n)].map((c) => (/\d/.test(c) ? `<span>${c}</span>` : `<span class="sep">${esc(c)}</span>`)).join('')}</div><em>${label}</em></div>`;
}

function barList(items, { label, href = () => null, empty = 'Nothing yet.' }) {
  if (!items.length) return `<p class="fine">${empty}</p>`;
  const max = Math.max(...items.map((i) => i[1]));
  return `<ol class="bar-list">${items.map(([k, n]) => {
    const h = href(k);
    const name = h ? `<a href="${esc(h)}">${esc(label(k))}</a>` : esc(label(k));
    return `<li><span class="bl-name">${name}</span><span class="bl-bar"><i style="width:${Math.max(2, (n / max) * 100).toFixed(1)}%"></i></span><b>${fmtN(n)}</b></li>`;
  }).join('')}</ol>`;
}

function dailyChart(series) {
  const W = 960, H = 240, L = 40, R = 8, T = 14, B = 26;
  const max = Math.max(4, ...series.map((d) => d.views));
  const step = Math.pow(10, Math.floor(Math.log10(max))) * (max / Math.pow(10, Math.floor(Math.log10(max))) > 5 ? 2 : 1);
  const top = Math.ceil(max / step) * step;
  const y = (v) => T + (H - T - B) * (1 - v / top);
  const bw = (W - L - R) / series.length;
  const grid = [];
  for (let v = 0; v <= top; v += step) grid.push(`<line x1="${L}" x2="${W - R}" y1="${y(v)}" y2="${y(v)}"/><text x="${L - 6}" y="${y(v) + 4}" text-anchor="end">${fmtN(v)}</text>`);
  const labelEvery = Math.ceil(series.length / 10);
  const md = (d) => new Date(`${d}T12:00:00Z`).toLocaleString('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' });
  const bars = series.map((d, i) => {
    const x = L + i * bw, w = Math.max(1, bw - 2), h = H - B - y(d.views);
    const tip = `${md(d.day)}: ${fmtN(d.views)} views · ${fmtN(d.visitors)} visitors${d.log ? ' (from server logs)' : ''}`;
    return `<g class="day${d.log ? ' log' : ''}" data-tip="${esc(tip)}"><rect class="hit" x="${x}" y="${T}" width="${bw}" height="${H - T - B}"/>${d.views ? `<path class="bar" d="M${x + 1} ${H - B}V${y(d.views) + Math.min(3, h)}q0 -3 3 -3h${w - 6}q3 0 3 3V${H - B}Z"/>` : ''}</g>${i % labelEvery === 0 ? `<text class="x" x="${x + bw / 2}" y="${H - 8}" text-anchor="middle">${md(d.day)}</text>` : ''}`;
  }).join('');
  const line = series.map((d, i) => `${i ? 'L' : 'M'}${(L + i * bw + bw / 2).toFixed(1)} ${y(d.visitors).toFixed(1)}`).join('');
  const dots = series.length <= 45 ? series.map((d, i) => `<circle cx="${(L + i * bw + bw / 2).toFixed(1)}" cy="${y(d.visitors).toFixed(1)}" r="3"/>`).join('') : '';
  return `<svg class="daily" viewBox="0 0 ${W} ${H}" role="img" aria-label="Views and visitors per day"><g class="grid">${grid.join('')}</g>${bars}<path class="vline" d="${line}"/><g class="vdots">${dots}</g></svg>`;
}

function heatMap(counts) {
  const max = Math.max(0, ...Object.values(counts));
  const shade = (n) => (n ? SEQ[Math.min(SEQ.length - 1, Math.floor((Math.log(n + 1) / Math.log(max + 1)) * SEQ.length - 1e-9))] : null);
  const paths = STATES.map((s) => {
    const n = counts[s.code] || 0, f = shade(n);
    return `<path d="${s.d}" class="hs${n ? ' on' : ''}"${f ? ` style="fill:${f}"` : ''} data-tip="${esc(s.name)}: ${n ? `${fmtN(n)} ${n === 1 ? 'view' : 'views'}` : 'no views yet'}"/>`;
  }).join('');
  const legend = max ? `<div class="heat-key"><span>fewer</span>${SEQ.map((c) => `<i style="background:${c}"></i>`).join('')}<span>more views</span></div>` : '';
  return `<svg class="usa heat" viewBox="0 0 975 610" role="img" aria-label="State page views">${paths}</svg>${legend}`;
}

