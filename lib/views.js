export const ASSET_VERSION = Date.now().toString(36);

function stateSilhouette(s, cls = '') {
  const [x0, y0, x1, y1] = s.b;
  const pad = Math.max(x1 - x0, y1 - y0) * 0.06;
  return `<svg class="silhouette ${cls}" viewBox="${x0 - pad} ${y0 - pad} ${x1 - x0 + pad * 2} ${y1 - y0 + pad * 2}" aria-hidden="true"><path d="${s.d}"/></svg>`;
}

function editorBits(author) {
  if (!author) return '';
  return `<script src="/js/editor.js?v=${ASSET_VERSION}" defer></script>`;
}

