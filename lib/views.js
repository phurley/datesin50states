export function adminPage({ author, codes, maps, msg, error }) {
  const day = (iso) => (iso ? iso.slice(0, 10) : '');
  const codeRow = (c) => `<form method="post" action="/admin/codes" class="code-row">
      <input type="hidden" name="orig" value="${esc(c.code)}">
      <input name="code" value="${esc(c.code)}" aria-label="Code">
      <span class="uses">${c.uses} /</span><input name="max_uses" type="number" min="0" value="${c.max_uses ?? ''}" placeholder="∞" aria-label="Max uses">
      <input name="expires_at" type="date" value="${day(c.expires_at)}" aria-label="Expires">
      <select name="active" aria-label="Active"><option value="1"${c.active ? ' selected' : ''}>Active</option><option value="0"${c.active ? '' : ' selected'}>Off</option></select>
      <input name="note" value="${esc(c.note || '')}" placeholder="Note" aria-label="Note">
      <button class="btn small">Save</button></form>`;
  const body = `
<main class="profile-main wide">
  <h1 class="page-title">Admin</h1>
  ${flash({ msg, error })}
  <section class="card">
    <h2>Join codes</h2>
    <div class="code-head"><span>Code</span><span>Used / max</span><span>Expires</span><span>Status</span><span>Note</span></div>
    ${codes.map(codeRow).join('')}
    <h3>New code</h3>
    ${codeRow({ code: '', uses: 0, max_uses: 100, expires_at: null, active: 1, note: '' })}
    <p class="fine">Blank max = unlimited; blank expiry = never.</p>
  </section>
  <section class="card">
    <h2>Maps (${maps.length})</h2>
    <table class="maps"><thead><tr><th>Address</th><th>Members</th><th>Entries</th><th>Photos</th><th>Created</th></tr></thead><tbody>
    ${maps.map((m) => `<tr><td><a href="/${esc(m.slug)}/">${esc(m.slug)}</a>${m.is_root ? ' <small class="tag">root</small>' : ''}</td><td>${esc(m.members || '—')}</td><td>${m.entries}</td><td>${m.photos}</td><td>${day(m.created_at)}</td></tr>`).join('')}
    </tbody></table>
  </section>
</main>`;
  return layout({ title: 'Admin', author, body, bodyClass: 'page-profile', noindex: true });
}

