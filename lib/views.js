export const ASSET_VERSION = Date.now().toString(36);

function stateSilhouette(s, cls = '', art = false) {
  const [x0, y0, x1, y1] = s.b;
  const pad = Math.max(x1 - x0, y1 - y0) * 0.06;
  // With art, the silhouette is filled with the state's illustration (same trick as the map).
  const fill = art ? `<defs><pattern id="sil-${s.code}" patternUnits="userSpaceOnUse" x="${x0}" y="${y0}" width="${x1 - x0}" height="${y1 - y0}"><image href="${stateArt(s.code)}" x="0" y="0" width="${x1 - x0}" height="${y1 - y0}" preserveAspectRatio="xMidYMid slice"/></pattern></defs>` : '';
  return `<svg class="silhouette ${cls}" viewBox="${x0 - pad} ${y0 - pad} ${x1 - x0 + pad * 2} ${y1 - y0 + pad * 2}" aria-hidden="true">${fill}<path d="${s.d}"${art ? ` style="fill:url(#sil-${s.code})"` : ''}/></svg>`;
}

function editorBits(canEdit) {
  if (!canEdit) return '';
  return `<script src="/js/editor.js?v=${ASSET_VERSION}" defer></script>`;
}

