export const STATES = JSON.parse(readFileSync(new URL('./usa-states.json', import.meta.url), 'utf8'));
export const STATE_BY_CODE = Object.fromEntries(STATES.map((s) => [s.code, s]));

// Vintage sticker palette for visited states, assigned by state so colors stay put.
const PALETTE = ['rust', 'orange', 'mustard', 'teal', 'olive', 'brick'];
const tone = (code) => PALETTE[(code.charCodeAt(0) * 7 + code.charCodeAt(1) * 3) % PALETTE.length];

// Default illustration per state (public/img/states, generated by scripts/gen-state-art.js).
export const stateArt = (code) => `/img/states/${code}.webp`;

export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

export function renderMarkdown(md) {
  return sanitizeHtml(marked.parse(md || '', { breaks: true }), {
    allowedTags: sanitizeHtml.defaults.allowedTags.concat(['img', 'h1', 'h2', 'del']),
    allowedAttributes: { a: ['href', 'title'], img: ['src', 'alt', 'title'] },
    transformTags: { a: sanitizeHtml.simpleTransform('a', { rel: 'noopener', target: '_blank' }) },
  });
}

function fmtDate(d) {
  if (!d) return null;
  const dt = new Date(`${d}T12:00:00Z`);
  if (Number.isNaN(dt.getTime())) return null;
  return {
    mon: dt.toLocaleString('en-US', { month: 'short', timeZone: 'UTC' }).toUpperCase(),
    day: dt.getUTCDate(),
    year: dt.getUTCFullYear(),
    long: dt.toLocaleString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }),
  };
}

