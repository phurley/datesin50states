function sparkline(series) {
  const W = 300, H = 44, max = Math.max(1, ...series.map((d) => d.views)), dx = W / Math.max(1, series.length - 1);
  const pts = series.map((d, i) => `${(i * dx).toFixed(1)} ${(H - 3 - (d.views / max) * (H - 6)).toFixed(1)}`);
  return `<svg class="spark" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none" aria-hidden="true"><path class="area" d="M0 ${H}L${pts.join('L')}L${W} ${H}Z"/><path class="ln" d="M${pts.join('L')}"/></svg>`;
}

